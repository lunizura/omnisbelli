// Tactical Military Glyphs (8x8)
static const uint8_t GLYPH_SKULL[8] = {
    0x3C, 0x7E, 0xDB, 0xFF, 0x7E, 0x3C, 0x24, 0x3C
};

static const uint8_t GLYPH_AQUILA[8] = {
    0x81, 0xC3, 0xE7, 0x7E, 0x3C, 0x18, 0x3C, 0x66
};

static const uint8_t GLYPH_COG[8] = {
    0x24, 0x7E, 0x99, 0xBD, 0xBD, 0x99, 0x7E, 0x24
};

static const uint8_t GLYPH_CROSSHAIR[8] = {
    0x18, 0x18, 0x00, 0x99, 0x99, 0x00, 0x18, 0x18
};

static const uint8_t GLYPH_BIOHAZARD[8] = {
    0x3C, 0x66, 0x99, 0xDB, 0xDB, 0x99, 0x66, 0x3C
};

static const uint8_t GLYPH_SHIELD[8] = {
    0xFE, 0xFE, 0xFE, 0x7C, 0x7C, 0x38, 0x10, 0x00
};

static const uint8_t GLYPH_WARNING[8] = {
    0x18, 0x18, 0x24, 0x24, 0x42, 0x5A, 0x7E, 0x00
};

static const uint8_t GLYPH_SWORD[8] = {
    0x02, 0x0C, 0x18, 0x30, 0x7E, 0x30, 0x48, 0x84
};

static const uint8_t GLYPH_CHOKEPOINT[8] = {
    0xE7, 0xC3, 0x81, 0x00, 0x00, 0x81, 0xC3, 0xE7
};

void BitmapFont::draw_char(
    PixelFramebuffer& fb,
    int x, int y,
    char c,
    uint32_t fg_color,
    uint32_t bg_color,
    bool transparent,
    int scale
) {
    if (scale <= 0) scale = 1;
    uint8_t index = static_cast<uint8_t>(c);
    if (index < 32 || index > 126) {
        index = 32; // Default to space
    }
    const uint8_t* rows = FONT_8X8[index - 32];

    for (int r = 0; r < 8; r++) {
        uint8_t row_bits = rows[r];
        for (int col = 0; col < 8; col++) {
            bool set = (row_bits & (0x80 >> col)) != 0;
            uint32_t col_val = set ? fg_color : bg_color;

            if (set || !transparent) {
                if (scale == 1) {
                    fb.set_pixel(x + col, y + r, col_val);
                } else {
                    for (int dy = 0; dy < scale; dy++) {
                        for (int dx = 0; dx < scale; dx++) {
                            fb.set_pixel(x + col * scale + dx, y + r * scale + dy, col_val);
                        }
                    }
                }
            }
        }
    }
}

void BitmapFont::draw_string(
    PixelFramebuffer& fb,
    int x, int y,
    const std::string& text,
    uint32_t fg_color,
    uint32_t bg_color,
    bool transparent,
    int scale
) {
    int cur_x = x;
    int cur_y = y;
    int char_w = 8 * scale;
    int char_h = 8 * scale;

    for (char c : text) {
        if (c == '\n') {
            cur_x = x;
            cur_y += char_h + scale;
            continue;
        }
        draw_char(fb, cur_x, cur_y, c, fg_color, bg_color, transparent, scale);
        cur_x += char_w;
    }
}

void BitmapFont::draw_glyph(
    PixelFramebuffer& fb,
    int x, int y,
    TacticalGlyph glyph,
    uint32_t fg_color,
    int scale
) {
    if (scale <= 0) scale = 1;
    const uint8_t* rows = nullptr;

    switch (glyph) {
    case TacticalGlyph::SKULL:            rows = GLYPH_SKULL; break;
    case TacticalGlyph::AQUILA:           rows = GLYPH_AQUILA; break;
    case TacticalGlyph::COG:              rows = GLYPH_COG; break;
    case TacticalGlyph::CROSSHAIR:        rows = GLYPH_CROSSHAIR; break;
    case TacticalGlyph::BIOHAZARD:        rows = GLYPH_BIOHAZARD; break;
    case TacticalGlyph::SHIELD:           rows = GLYPH_SHIELD; break;
    case TacticalGlyph::WARNING_TRIANGLE: rows = GLYPH_WARNING; break;
    case TacticalGlyph::SWORD:            rows = GLYPH_SWORD; break;
    case TacticalGlyph::CHOKEPONT_ICON:   rows = GLYPH_CHOKEPOINT; break;
    default:                              rows = GLYPH_CROSSHAIR; break;
    }

    for (int r = 0; r < 8; r++) {
        uint8_t row_bits = rows[r];
        for (int col = 0; col < 8; col++) {
            if ((row_bits & (0x80 >> col)) != 0) {
                if (scale == 1) {
                    fb.set_pixel(x + col, y + r, fg_color);
                } else {
                    for (int dy = 0; dy < scale; dy++) {
                        for (int dx = 0; dx < scale; dx++) {
                            fb.set_pixel(x + col * scale + dx, y + r * scale + dy, fg_color);
                        }
                    }
                }
            }
        }
    }
}

int BitmapFont::get_string_width(const std::string& text, int scale) {
    return static_cast<int>(text.length()) * 8 * scale;
}

int BitmapFont::get_char_height(int scale) {
    return 8 * scale;
}

